def _warn_deprecated(old: str, provider: str) -> None:
    """Emit the standard deprecation warning for a provider-specific analyzer."""
    warnings.warn(
        f'{old} is deprecated and will be removed in rapidtools 0.2; use '
        f"AssetAnalyzer(rapidtools.models.load('{provider}', ...), prompt=...) "
        'instead.',
        DeprecationWarning,
        stacklevel=3,
    )


class BaseAPIAssetAnalyzer(AssetAnalyzer):
    """
    Deprecated base for hosted-API analyzers; builds the model from ``MODEL_CLASS``.

    Prefer :class:`AssetAnalyzer` with :func:`rapidtools.models.load`.

    Example:
        >>> analyzer = GeminiAssetAnalyzer(api_key='...', prompt='Rate it 0-5.')
        >>> collection = analyzer(collection)
    """

    MODEL_CLASS: type = GeminiInference
    ATTRIBUTE_PREFIX = 'gemini'
    PROVIDER_NAME = 'Gemini API'
    DEFAULT_MODEL_ID: str | None = None

    def __init__(
        self,
        api_key: str | Path | None = None,
        prompt: str | Path = '',
        model_id: str | None = None,
        max_workers: int | None = 5,
        max_retries: int | None = 3,
        cooldown_duration: int | None = 30,
        system_instruction: str | None = None,
        temperature: float = 0.4,
        max_tokens: int = 2048,
        image_filter: Callable[[ImageAsset], bool] | None = None,
        cancel_event: threading.Event | None = None,
    ):
        """
        Build the provider model and wrap it in an :class:`AssetAnalyzer`.

        Args:
            api_key: Provider API key (or path to a file containing it).
            prompt: Text prompt or path to a prompt file.
            model_id: Provider model ID. Defaults to the provider's default.
            max_workers: Concurrent threads. Defaults to 5.
            max_retries: Retries per individual request. Defaults to 3.
            cooldown_duration: Base seconds to wait on rate limit. Defaults to 30.
            system_instruction: Optional model persona/constraints.
            temperature: Randomness (0.0 to 2.0).
            max_tokens: Maximum output length.
            image_filter: Optional function to filter ImageAssets.
            cancel_event: Optional ``threading.Event``; when set, the analyzer
                stops submitting requests and raises ``OperationCancelled``.
        """
        _warn_deprecated(type(self).__name__, type(self).ATTRIBUTE_PREFIX)
        self.max_retries = max_retries
        model_kwargs: dict[str, Any] = dict(
            api_key=api_key,
            max_workers=max_workers,
            max_retries=max_retries,
            system_instruction=system_instruction,
            temperature=temperature,
            max_tokens=max_tokens,
        )
        chosen = model_id or self.DEFAULT_MODEL_ID
        if chosen:
            model_kwargs['model_id'] = chosen
        model = self.MODEL_CLASS(**model_kwargs)
        super().__init__(
            model,
            prompt=prompt,
            attribute_prefix=type(self).ATTRIBUTE_PREFIX,
            max_workers=max_workers,
            image_filter=image_filter,
            cancel_event=cancel_event,
            rate_limit=RateLimitPolicy(cooldown_duration or 0),
            mode='api',
        )


