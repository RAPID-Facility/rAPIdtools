"""
Pipeline components that describe assets with vision-language models.

:class:`AssetAnalyzer` is the single analysis step: give it any model from
:mod:`rapidtools.models` (hosted API or local checkpoint) and a prompt, and it
sends each asset's images to the model, parses the reply into key/value
attributes (``<prefix>_<key>``) and returns the mutated collection. Hosted
models run in a thread pool with a shared rate-limit cooldown; local models
run sequentially or in batches to protect GPU memory.

The provider-specific classes (``GeminiAssetAnalyzer``, ``Gemma4AssetAnalyzer``,
...) remain as thin, deprecated wrappers that build the model for you.

Example:
    >>> from rapidtools import Pipeline
    >>> from rapidtools.models import load
    >>> from rapidtools.processing import AssetAnalyzer
    >>> analyzer = AssetAnalyzer(
    ...     load('gemini', api_key='AIza...'), prompt='Rate the damage 0-5 as JSON.'
    ... )
    >>> collection = Pipeline([analyzer]).run(collection)
    >>> collection.get('bldg_01').attributes['gemini_damage']
    '3'
"""

