class BaseLocalAssetAnalyzer(AssetAnalyzer):
    """
    Compatibility alias for :class:`AssetAnalyzer` in local (sequential) mode.

    Example:
        >>> analyzer = BaseLocalAssetAnalyzer(Gemma4Inference(), prompt='Rate it.')
        >>> collection = analyzer(collection)
    """

    ATTRIBUTE_PREFIX = 'vlm'
    PROVIDER_NAME = 'Local VLM'

    def __init__(
        self,
        model: Any,
        prompt: str | Path = '',
        max_images_per_asset: int = 2,
        batch_size: int = 4,
        image_filter: Callable[[ImageAsset], bool] | None = None,
        cancel_event: threading.Event | None = None,
        attribute_prefix: str | None = None,
    ) -> None:
        """
        Wrap an already-loaded local model.

        Args:
            model: A local inference model exposing ``run_inference`` (and
                optionally ``run_inference_batch``) plus a ``model_id``.
            prompt: Text instruction or path to a prompt file.
            max_images_per_asset: Safeguard limit on images passed per asset.
            batch_size: Assets processed simultaneously when the model
                supports batching.
            image_filter: Optional function to filter ``ImageAsset`` objects.
            cancel_event: Optional ``threading.Event`` checked between batches.
            attribute_prefix: Overrides the class-level ``ATTRIBUTE_PREFIX``.
        """
        super().__init__(
            model,
            prompt=prompt,
            attribute_prefix=attribute_prefix or type(self).ATTRIBUTE_PREFIX,
            batch_size=batch_size,
            max_images_per_asset=max_images_per_asset,
            image_filter=image_filter,
            cancel_event=cancel_event,
            mode='local',
        )


