def parse_structured_results(text: str) -> dict[str, Any]:
    """
    Extract key-value pairs from a vision-language model response.

    Attempts to parse a JSON block (wrapped in ```json ... ``` or bare). If no
    JSON object is found, falls back to line-by-line ``Key: Value`` parsing,
    normalising keys to ``snake_case``.

    Args:
        text: The raw text generated by the model.

    Returns:
        dict[str, Any]: The parsed attributes (empty if nothing matched).

    Example:
        >>> parse_structured_results('```json\\n{"level": 3}\\n```')
        {'level': 3}
        >>> parse_structured_results('CHS Level: 3\\nNote - fine')
        {'chs_level': '3', 'note': 'fine'}
    """
    results: dict[str, Any] = {}

    json_match = re.search(r'```json\s*(.*?)\s*```', text, re.DOTALL)
    json_text = json_match.group(1) if json_match else text
    try:
        parsed = json.loads(json_text)
        if isinstance(parsed, dict):
            return parsed
    except json.JSONDecodeError:
        pass

    for line in text.split('\n'):
        match = re.match(r'^([\w\s]+)[:\-]\s*(.*)$', line.strip())
        if match:
            key = match.group(1).strip().lower().replace(' ', '_')
            results[key] = match.group(2).strip()
    return results


@dataclass
class RateLimitPolicy:
    """
    Shared back-off applied by :class:`AssetAnalyzer` to hosted APIs.

    When a request fails (rate limit, transient error, safety block), every
    worker pauses for ``cooldown_seconds`` multiplied by the number of
    consecutive failures; the first success resets the multiplier.

    Assets whose request failed are retried in additional passes once the
    first pass is complete (``max_asset_retries``), so a burst of 429s or
    timeouts does not leave holes in the results.

    Attributes:
        cooldown_seconds: Base pause after a failure. ``0`` disables pausing.
        max_asset_retries: Extra passes over the assets that failed.
            ``0`` disables retries.

    Example:
        >>> RateLimitPolicy(cooldown_seconds=10).wait_for(3)
        30
        >>> RateLimitPolicy(max_asset_retries=1).max_asset_retries
        1
    """

    cooldown_seconds: float = 30.0
    max_asset_retries: int = 2

    def wait_for(self, consecutive_errors: int) -> float:
        """Return the pause (seconds) after ``consecutive_errors`` failures."""
        return self.cooldown_seconds * consecutive_errors


class AssetAnalyzer:
    """
    Describe every asset in a collection with a vision-language model.

    Args:
        model (BaseInferenceModel):
            Any rapidtools model wrapper (see :func:`rapidtools.models.load`).
        prompt (str | Path):
            Prompt text or path to a prompt file applied to every asset.
        attribute_prefix (str | None):
            Prefix of the attributes written to each asset. Defaults to the
            provider's prefix (``'gemini'``, ``'qwen_vl'``, ...).
        max_workers (int | None):
            Concurrent requests for hosted models. Defaults to 5 for APIs and
            1 for local models (local inference is never threaded).
        batch_size (int):
            Assets per batch when the model offers ``run_inference_batch``.
            Defaults to 4.
        max_images_per_asset (int | None):
            Cap on the images sent per asset; ``None`` sends them all.
        image_filter (Callable[[ImageAsset], bool] | None):
            Optional predicate selecting which images to analyze.
        cancel_event (threading.Event | None):
            Cooperative cancellation flag checked between assets/batches.
        rate_limit (RateLimitPolicy | None):
            Back-off and retry policy for hosted models; ``None`` uses a
            30-second cooldown with two retry passes for APIs and no cooldown
            for local models.
        generation (GenerationConfig | None):
            Per-call generation options (``json_mode``, ``temperature``, ...)
            forwarded to the model.
        mode (str | None):
            Force ``'api'`` (threaded) or ``'local'`` (sequential/batched)
            execution; inferred from the model when ``None``.

    Example:
        >>> from rapidtools.models import GenerationConfig, load
        >>> from rapidtools.processing import AssetAnalyzer
        >>> analyzer = AssetAnalyzer(
        ...     load('qwen_vl', model_id='Qwen/Qwen3.5-9B', load_in_4bit=True),
        ...     prompt='Return JSON with a damage_level key.',
        ...     batch_size=4,
        ...     generation=GenerationConfig(json_mode=True, temperature=0.0),
        ... )
        >>> collection = analyzer(collection)
        >>> collection.get('bldg_01').attributes['qwen_vl_damage_level']
        'moderate'
    """

    stage = Stage.ANALYZE

    #: Default attribute prefix when neither the model nor the caller gives one.
    ATTRIBUTE_PREFIX: str | None = None
    PROVIDER_NAME: str | None = None

    def __init__(
        self,
        model: BaseInferenceModel,
        prompt: str | Path = '',
        attribute_prefix: str | None = None,
        max_workers: int | None = None,
        batch_size: int = 4,
        max_images_per_asset: int | None = None,
        image_filter: Callable[[ImageAsset], bool] | None = None,
        cancel_event: threading.Event | None = None,
        rate_limit: RateLimitPolicy | None = None,
        generation: GenerationConfig | None = None,
        mode: str | None = None,
    ) -> None:
        """Wrap ``model`` for use as the analysis step of a pipeline."""
        self.model = model
        self.prompt = resolve_prompt_text(prompt)
        self.image_filter = image_filter
        self.cancel_event = cancel_event
        self.generation = generation
        self.max_images_per_asset = max_images_per_asset
        self.batch_size = max(1, batch_size)

        info = getattr(model, 'INFO', None)
        if mode is None:
            if info is not None and info.kind in ('api', 'local'):
                mode = info.kind
            elif isinstance(model, BaseLocalInferenceModel):
                mode = 'local'
            else:
                mode = 'api'
        if mode not in ('api', 'local'):
            raise ValueError(f"mode must be 'api' or 'local', got {mode!r}.")
        self.mode = mode

        prefix = attribute_prefix or type(self).ATTRIBUTE_PREFIX
        if not prefix:
            prefix = info.attribute_prefix if info is not None else 'vlm'
        self.ATTRIBUTE_PREFIX = prefix or 'vlm'
        self.PROVIDER_NAME = type(self).PROVIDER_NAME or (
            info.label if info is not None else 'VLM'
        )

        if max_workers is None:
            max_workers = 5 if self.mode == 'api' else 1
        self.max_workers = max(1, max_workers)

        if rate_limit is None:
            rate_limit = RateLimitPolicy() if self.mode == 'api' else RateLimitPolicy(0)
        self.rate_limit = rate_limit
        self._lock = threading.Lock()
        self._global_cooldown_until = 0.0
        self._consecutive_error_count = 0
        # IDs of assets the provider rejected outright (refusal, 4xx, safety
        # block): they are reported as failed but neither pause the workers
        # nor get another pass.
        self._permanent_failures: set[str] = set()

        self.model_id = getattr(model, 'model_id', None)

    # ------------------------------------------------------------ properties
    @property
    def attribute_prefix(self) -> str:
        """Prefix of the attributes written to each asset."""
        # ``__init__`` always stores a non-empty prefix; the class attribute
        # is Optional only so subclasses may leave it unset.
        return self.ATTRIBUTE_PREFIX or 'vlm'

    @property
    def cooldown_duration(self) -> float:
        """Base cooldown in seconds (from :attr:`rate_limit`)."""
        return self.rate_limit.cooldown_seconds

    # --------------------------------------------------------------- helpers
    def _parse_structured_results(self, text: str) -> dict[str, Any]:
        """Extract key-value pairs from the model response."""
        return parse_structured_results(text)

    def _image_paths(self, asset: PhysicalAsset) -> list[Path]:
        """Return the downloaded image paths of an asset after filtering/capping."""
        target_images = asset.image_assets
        if self.image_filter is not None:
            target_images = target_images.filter(self.image_filter)
        paths = [img.path for img in target_images if img.is_downloaded]
        if self.max_images_per_asset is not None:
            paths = paths[: self.max_images_per_asset]
        return paths

    def _infer(self, image_paths: list[Path], prompt: str) -> Any:
        """Call the model, forwarding the generation config when one is set."""
        if self.generation is not None:
            return self.model.run_inference(
                image_inputs=image_paths, prompt=prompt, config=self.generation
            )
        return self.model.run_inference(image_inputs=image_paths, prompt=prompt)

    def _apply_result(self, asset: PhysicalAsset, img_paths: list, result: Any) -> bool:
        """Write a model response onto the asset; return ``True`` on success."""
        if result is None or not result.text:
            return False
        structured_data = self._parse_structured_results(result.text)
        prefix = self.ATTRIBUTE_PREFIX
        if structured_data:
            for key, val in structured_data.items():
                asset.attributes[f'{prefix}_{key}'] = val
        else:
            asset.attributes[f'{prefix}_analysis_raw'] = result.text
        asset.attributes['ai_model_used'] = getattr(self.model, 'model_id', None)
        asset.attributes['images_analyzed_count'] = len(img_paths)
        return True

    # ------------------------------------------------------------- API mode
    def _process_single_asset(self, asset: PhysicalAsset) -> bool:
        """
        Analyze one asset, honouring the shared rate-limit cooldown.

        Returns:
            bool: ``True`` when attributes were written.
        """
        if is_cancelled(self.cancel_event):
            return False

        with self._lock:
            wait_time = self._global_cooldown_until - time.time()
        if wait_time > 0:
            logger.debug(
                f'Asset {asset.id} delayed: global cooldown active for '
                f'{int(wait_time)}s...'
            )
            time.sleep(wait_time)

        image_paths = self._image_paths(asset)
        if not image_paths:
            return False

        result = self._infer(image_paths, self.prompt)

        if (
            result is not None
            and getattr(result, 'failed', False)
            and not getattr(result, 'retryable', True)
        ):
            # A rejection is not a rate limit: do not stall the other workers
            # or re-send the same request later.
            logger.error(
                f'Asset {asset.id} was rejected by the provider ({result.error}); '
                'it will not be retried.'
            )
            with self._lock:
                self._permanent_failures.add(asset.id)
            return False

        if result is None or not result.text:
            with self._lock:
                self._consecutive_error_count += 1
                dynamic_wait = self.rate_limit.wait_for(self._consecutive_error_count)
                if dynamic_wait > 0:
                    self._global_cooldown_until = time.time() + dynamic_wait
                logger.warning(
                    f'Request failed for asset {asset.id} (consecutive failures: '
                    f'{self._consecutive_error_count}); pausing all workers for '
                    f'{dynamic_wait:g}s. The asset will be retried later.'
                )
            return False

        with self._lock:
            if self._consecutive_error_count > 0:
                logger.info('Successful response received. Resetting error multiplier.')
                self._consecutive_error_count = 0

        return self._apply_result(asset, image_paths, result)

    def _run_pass(
        self, assets: list[PhysicalAsset], description: str
    ) -> list[PhysicalAsset]:
        """Analyze ``assets`` concurrently and return the ones that failed."""
        workers = min(self.max_workers, max(1, len(assets)))
        failed: list[PhysicalAsset] = []
        with ThreadPoolExecutor(max_workers=workers) as executor:
            future_to_asset = {
                executor.submit(self._process_single_asset, asset): asset
                for asset in assets
            }
            for future in tqdm(
                as_completed(future_to_asset), total=len(assets), desc=description
            ):
                asset = future_to_asset[future]
                if is_cancelled(self.cancel_event):
                    executor.shutdown(wait=False, cancel_futures=True)
                    break
                try:
                    if not future.result() and asset.id not in self._permanent_failures:
                        failed.append(asset)
                except Exception as e:  # noqa: BLE001 - reported per asset
                    logger.error(f'Error on asset {asset.id}: {e}')
                    failed.append(asset)
        return failed

    def _run_api(self, assets: list[PhysicalAsset]) -> int:
        """
        Analyze assets concurrently with retry passes; return the failures.

        Assets without downloaded images are skipped up front. Assets whose
        request failed transiently (rate limit, timeout, network error) are
        retried in up to ``rate_limit.max_asset_retries`` further passes;
        assets the provider rejected (refusal, safety block, 4xx) are counted
        as failed without a retry.
        """
        self._permanent_failures = set()
        pending = [asset for asset in assets if self._image_paths(asset)]
        skipped = len(assets) - len(pending)
        if skipped:
            logger.info(f'{skipped} assets have no downloaded images and are skipped.')
        workers = min(self.max_workers, max(1, len(pending)))
        logger.info(
            f'{self.PROVIDER_NAME}: analyzing {len(pending)} assets with {workers} '
            f'workers (base cooldown: {self.cooldown_duration:g}s, up to '
            f'{self.rate_limit.max_asset_retries} retry passes).'
        )
        failed: list[PhysicalAsset] = []
        for attempt in range(1 + max(0, self.rate_limit.max_asset_retries)):
            if not pending or is_cancelled(self.cancel_event):
                break
            description = (
                'Analyzing Assets' if attempt == 0 else f'Retry pass {attempt}'
            )
            if attempt > 0:
                logger.info(
                    f'Retrying {len(pending)} assets that failed (pass {attempt} of '
                    f'{self.rate_limit.max_asset_retries})...'
                )
            failed = self._run_pass(pending, description)
            pending = failed
        if failed:
            logger.error(
                f'{len(failed)} assets still failed after all retries: '
                f'{", ".join(a.id for a in failed[:10])}'
                f'{"..." if len(failed) > 10 else ""}'
            )
        if self._permanent_failures:
            logger.error(
                f'{len(self._permanent_failures)} assets were rejected by the '
                'provider and not retried.'
            )
        return len(failed) + len(self._permanent_failures) + skipped

    # ----------------------------------------------------------- local mode
    def _run_local(self, assets: list[PhysicalAsset]) -> int:
        """Analyze assets sequentially or in batches; return the failures."""
        run_inference_batch = getattr(self.model, 'run_inference_batch', None)
        batched = run_inference_batch is not None
        batch_size = self.batch_size if batched else 1
        total_batches = math.ceil(len(assets) / batch_size)
        logger.info(
            f'{self.PROVIDER_NAME}: analyzing {len(assets)} assets in batches of '
            f'{batch_size}...'
        )
        failed = 0
        for i in tqdm(
            range(0, len(assets), batch_size),
            total=total_batches,
            desc='Batch Analysis',
        ):
            raise_if_cancelled(self.cancel_event, f'{self.PROVIDER_NAME} analysis')
            batch_assets = assets[i : i + batch_size]
            batch_images = [self._image_paths(a) for a in batch_assets]

            if run_inference_batch is not None:
                kwargs = {'config': self.generation} if self.generation else {}
                results = run_inference_batch(
                    batch_images, [self.prompt] * len(batch_assets), **kwargs
                )
            else:
                results = [
                    self._infer(paths, self.prompt) if paths else None
                    for paths in batch_images
                ]

            for asset, img_paths, result in zip(
                batch_assets, batch_images, results, strict=True
            ):
                if not self._apply_result(asset, img_paths, result):
                    failed += 1

            self._release_gpu_memory()
        return failed

    @staticmethod
    def _release_gpu_memory() -> None:
        """Clear the CUDA cache between batches when PyTorch is available."""
        try:
            import torch
        except ImportError:  # pragma: no cover - torch is a dependency
            return
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    # -------------------------------------------------------------- __call__
    def __call__(
        self, asset_collection: PhysicalAssetCollection
    ) -> PhysicalAssetCollection:
        """
        Analyze every asset that has downloaded images.

        Args:
            asset_collection: The assets to describe.

        Returns:
            PhysicalAssetCollection: The same collection with new attributes.

        Raises:
            OperationCancelled: If ``cancel_event`` is set during the run.
        """
        assets_with_images = [a for a in asset_collection if len(a.image_assets) > 0]
        if not assets_with_images:
            logger.warning('No assets with images found to analyze. Skipping.')
            return asset_collection

        if self.mode == 'api':
            failed = self._run_api(assets_with_images)
        else:
            failed = self._run_local(assets_with_images)

        raise_if_cancelled(self.cancel_event, f'{self.PROVIDER_NAME} analysis')

        if failed > 0:
            logger.error(f'{self.PROVIDER_NAME}: {failed} assets failed to process.')
        else:
            logger.info(f'{self.PROVIDER_NAME}: All assets processed successfully.')
        return asset_collection


